export function getServiceTaxonomyLabel(slug, language = 'uz') {
  const entry = LABELS[String(slug || '').toLowerCase()];
  if (!entry) {
    return String(slug || '').replace(/[-_]/g, ' ').replace(/^./, (letter) => letter.toLocaleUpperCase());
  }
  const languageIndex = language.startsWith('ru') ? 1 : language.startsWith('en') ? 2 : 0;
  return entry[languageIndex];
}
